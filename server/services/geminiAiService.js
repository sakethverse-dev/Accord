const GEMINI_API_KEY = process.env.GEMINI_API_KEY;

/**
 * Call Google Gemini REST endpoint directly
 */
async function callGemini(prompt, systemInstruction = '', jsonMode = true) {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error('GEMINI_API_KEY is not configured in server environment.');
  }

  // Primary model: gemini-2.5-flash, Fallback: gemini-1.5-flash
  const models = ['gemini-2.5-flash', 'gemini-1.5-flash'];
  let lastError = null;

  for (const model of models) {
    try {
      const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
      const payload = {
        contents: [{
          parts: [{ text: prompt }]
        }],
        generationConfig: {
          temperature: 0.2,
          topP: 0.8,
        }
      };

      if (systemInstruction) {
        payload.systemInstruction = {
          parts: [{ text: systemInstruction }]
        };
      }

      if (jsonMode) {
        payload.generationConfig.responseMimeType = 'application/json';
      }

      const response = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.error?.message || `Gemini API HTTP ${response.status}`);
      }

      const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
      if (!text) {
        throw new Error('No content generated by Gemini');
      }

      if (jsonMode) {
        // Clean markdown backticks if any
        const cleaned = text.replace(/^```json\s*/i, '').replace(/```\s*$/i, '').trim();
        return JSON.parse(cleaned);
      }

      return text;
    } catch (err) {
      lastError = err;
      console.warn(`[GeminiAI] Model ${model} failed, attempting next if available:`, err.message);
    }
  }

  throw lastError;
}

/**
 * Analyze and Reconcile Party A Draft vs Party B Draft without fixed rules
 */
async function analyzeAndReconcileDraftsWithAI(draftAText, draftBText, creatorRole = 'freelancer', invitedRole = 'client') {
  const prompt = `
You are an expert impartial contract attorney and mediator.
Compare the following two contract drafts submitted by Party A (${creatorRole}) and Party B (${invitedRole}).

Do NOT use rigid fixed rules. Read their actual words and analyze what each party expects.
Extract every major topic/clause (e.g., Payment Terms, Deliverables & Acceptance, Intellectual Property, Liability & Indemnification, Termination & Notice, Non-Compete / Exclusivity, Confidentiality, Warranties, Governing Law).

For each topic/clause:
1. Identify Party A's position/text and Party B's position/text.
2. Determine if their terms conflict or differ.
3. If they conflict or present severe risk, evaluate the riskLevel:
   - "CRITICAL": High financial risk, uncapped exposure, immediate forfeiture of rights, or extreme unbalance.
   - "WARNING": Minor imbalance, ambiguity in timelines, or standard negotiation points.
   - "SAFE": Both parties are well-aligned or terms are standard and fair.
4. Detail the exact riskReason (explaining what differs and why it creates friction).
5. Synthesize a professional, legally binding "suggestedReplacement" (AI Balanced Compromise) that bridges their gap fairly, protecting both the freelancer's livelihood and the client's business interests.
6. Provide a "compromiseRationale" explaining why both sides should accept this middle ground.

Return a STRICT JSON object in this exact schema:
{
  "summary": "Concise 2-sentence executive summary of the negotiation differences",
  "alignmentScore": 75,
  "clauses": [
    {
      "sectionNumber": "1.0",
      "title": "Payment Terms & Invoicing",
      "partyAText": "...",
      "partyBText": "...",
      "currentText": "...",
      "category": "PAYMENT",
      "riskLevel": "WARNING",
      "riskReason": "Party A requested Net-15 upon delivery while Party B proposed Net-60.",
      "suggestedReplacement": "Invoices shall be payable within thirty (30) calendar days of verified milestone delivery.",
      "compromiseRationale": "Net-30 provides a standard business accounting cycle for the client while ensuring predictable cash flow for the freelancer."
    }
  ]
}

Party A (${creatorRole}) Draft:
"""
${draftAText || '(No draft text provided)'}
"""

Party B (${invitedRole}) Draft:
"""
${draftBText || '(No draft text provided)'}
"""
`;

  const systemInstruction = 'You are an institutional contract reconciliation and negotiation engine. You always output valid, parseable JSON conforming to the requested schema. You do not use fixed rules, but analyze the semantic intent and legal risk of the parties.';

  return await callGemini(prompt, systemInstruction, true);
}

/**
 * Audit raw unstructured agreement text for a single party
 */
async function auditDraftWithAI(rawText, userRole = 'freelancer') {
  const prompt = `
You are an expert contract risk auditor reviewing an agreement on behalf of a ${userRole}.
Do NOT use fixed rigid rules. Instead, parse this contract into distinct clauses, identify risks or one-sided traps specific to a ${userRole}, and provide balanced suggestions.

Return a STRICT JSON object in this exact schema:
{
  "title": "Suggested Contract Title",
  "alignmentScore": 80,
  "clauses": [
    {
      "sectionNumber": "1.0",
      "title": "Clause Title",
      "currentText": "Original clause text",
      "category": "GENERAL",
      "riskLevel": "SAFE" | "WARNING" | "CRITICAL",
      "riskReason": "Explanation if risky, empty string if safe",
      "suggestedReplacement": "Improved balanced clause text if risky, empty string if safe"
    }
  ]
}

Contract Text:
"""
${rawText}
"""
`;

  const systemInstruction = 'You are an institutional contract auditing AI. Output strictly valid JSON.';
  return await callGemini(prompt, systemInstruction, true);
}

/**
 * Rewrite or improve a specific clause interactively based on user instruction
 */
async function improveClauseWithAI({ clauseTitle, currentText, instruction, userRole = 'freelancer' }) {
  const prompt = `
You are an expert contract attorney assisting a ${userRole}.
Improve and rewrite the following contract clause based on the user's specific instruction.

Clause Title: "${clauseTitle}"
Current Clause Text:
"""
${currentText}
"""

User Instruction: "${instruction || 'Make this clause balanced, fair, and clear for both parties.'}"

Return a STRICT JSON object:
{
  "improvedText": "The newly drafted, legally sound, and improved clause text.",
  "rationale": "Clear 1-2 sentence explanation of what changes were made and how it satisfies the instruction."
}
`;

  return await callGemini(prompt, 'You are an expert legal drafting assistant. Output strictly valid JSON.', true);
}

